/**
 * `@ltr8/tson/stdlib` — the four bundled schemas, embedded and registered.
 *
 * The point of these is not that the schemas parse (`bundled-schemas-parse.test.ts` and
 * `bundled-schemas-resolve.test.ts` already own that against `spec/m/` directly) but that the
 * *embedded copies* are the same documents, and that registering them produces a `Tson` a caller
 * can immediately resolve a user schema against — which is the whole reason this subpath exists.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

import {
  CORE_TN,
  META_TN,
  NET_TN,
  NUMERIC_TN,
  POLICY_TN,
  TEMPORAL_TN,
  registerStandardLibrary,
  standardLibrary,
} from '../src/stdlib/index.js';
import { createTson } from '../src/config.js';
import { declaredSha256, sha256HexSync } from '../src/link/contentHash.js';
import { canonicalizeIdentity } from '../src/link/identity.js';
import { encodeUtf8 } from '../src/io/utf8.js';

const SPEC_M = join(import.meta.dirname, '../../../spec/m');

describe('the embedded copies are the vendored documents', () => {
  it.each([
    ['meta.tn', META_TN],
    ['numeric.tn', NUMERIC_TN],
    ['temporal.tn', TEMPORAL_TN],
    ['net.tn', NET_TN],
    ['core.tn', CORE_TN],
    ['policy.tn', POLICY_TN],
  ])('%s matches spec/m/ byte for byte', (file, embedded) => {
    // Generated by scripts/gen-stdlib-schemas.mjs. A drift here means the generator was not re-run
    // after the vendored spec moved, and every schema resolved against the embedded copy would be
    // resolved against the wrong revision.
    expect(embedded).toBe(readFileSync(join(SPEC_M, file), 'utf8'));
  });
});

describe('standardLibrary()', () => {
  // Built from the embedded documents' own `!!id` values rather than from a hard-coded revision
  // string, so this schema follows `spec/m/` when the vendored pin moves.
  const idOf = (text: string): string => {
    const id = /^!!id:"([^"]+)"/u.exec(text)?.[1];
    if (id === undefined) throw new Error('a bundled schema carries no readable !!id');
    return id;
  };

  const USER_SCHEMA = `!!id:"https://example.com/reading.tn"
!!import:"${idOf(CORE_TN)}"
!schema {
  reading => {
    label: text
  }
}
`;

  it('registers all three, so a user schema resolves with no SchemaSource at all', () => {
    // The whole gap this closes: before it, a fresh Tson had an empty registry and this threw for
    // an unregistered !!meta. Note there is no `preload` and no source -- nothing fetches.
    const tson = standardLibrary();
    expect(() => tson.resolveSchema(USER_SCHEMA)).not.toThrow();
  });

  it('compiles what it resolves, end to end', () => {
    const tson = standardLibrary();
    const compiled = tson.compile(tson.resolveSchema(USER_SCHEMA));
    const value = tson.readTree(new TextEncoder().encode('{ label: "north ridge" }'), {
      schema: compiled,
      root: 'reading',
    });
    expect(value).toMatchObject({ kind: 'record', typeRef: 'reading' });
  });

  it('hands back a distinct registry each call, never a shared singleton', () => {
    // A registry is mutable state. Two callers sharing one would see each other's registrations,
    // and a test registering a schema would leak into the next.
    const first = standardLibrary();
    const second = standardLibrary();
    first.resolveSchema(USER_SCHEMA);
    expect(first).not.toBe(second);
    // `second` never saw the user schema, so resolving it there is still a first registration.
    expect(() => second.resolveSchema(USER_SCHEMA)).not.toThrow();
  });

  it('registerStandardLibrary returns the same instance it was given, for chaining', () => {
    const tson = createTson({});
    expect(registerStandardLibrary(tson)).toBe(tson);
  });
});

describe('the standard library carries its own key annotations (§6)', () => {
  const tson = standardLibrary();
  const kernel = [...tson.schemas.values()].find((s) => s.id.includes('/m/meta.tn'));

  it('registers the kernel with its @doc values on its entries (§3.4, §6)', () => {
    expect(kernel).toBeDefined();
    const doc = kernel?.keyAnnotations.get('meta.top')?.find((a) => a.name === 'doc');
    expect(doc?.value).toBeDefined();
  });

  it('marks every sugar-lifted entry @synthetic (§8.2)', () => {
    const synthetic = [...(kernel?.keyAnnotations ?? [])].filter(([, annotations]) =>
      annotations.some((a) => a.name === 'meta.synthetic'),
    );
    expect(synthetic.length).toBeGreaterThan(0);
  });

  it("reads the kernel's own @doc as the text the author wrote, the kernel having no governing annotation reader (§6)", () => {
    // The annotation's type is declared in the very document being read, so there is no compiled
    // reader to read its value through yet: it is read by its base type, the text itself.
    const doc = kernel?.keyAnnotations.get('meta.top')?.find((a) => a.name === 'doc');
    expect(doc?.value).toMatch(/^The structural root: every constructor IS-A `top`/u);
  });

  it("reads a library's @doc through the compiled reader of the schema declaring `doc`, an atom node (§6)", () => {
    const core = [...tson.schemas.values()].find((s) => s.id.includes('/m/core.tn'));
    const doc = core?.keyAnnotations.get('title')?.find((a) => a.name === 'doc');
    expect(doc?.value).toMatchObject({ kind: 'atom' });
  });
});

describe('policy.tn, the processor-policy vocabulary ([TSON-DATA] §8.2)', () => {
  const POLICY_ID = /^!!id:"([^"]+)"/u.exec(POLICY_TN)?.[1] ?? '';

  it('carries a pinned identity that is the digest of its own content (§2.2.1)', () => {
    expect(declaredSha256(POLICY_ID)).toBe(sha256HexSync(encodeUtf8(POLICY_TN)));
  });

  it('is registered by the standard library and served by identity, like meta and core', () => {
    const tson = standardLibrary();
    const linked = tson.schemas.get(canonicalizeIdentity(POLICY_ID));
    expect(linked).toBeDefined();
    expect([...(linked?.entries.keys() ?? [])]).toEqual(
      expect.arrayContaining([
        'policy',
        'policy.restriction_level',
        'policy.script_policy',
        'policy.identifier_policy',
      ]),
    );
  });

  it('resolves under the default name policy, its own names and imports included', () => {
    expect(() => standardLibrary().resolveSchema(POLICY_TN)).not.toThrow();
  });
});
